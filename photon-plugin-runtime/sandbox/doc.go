// Package sandbox — изоляция процесса плагина.
//
// Спецификация: docs/threat-model.md (раздел 4 — два уровня гарантий,
// раздел 5 — sandbox != authorization).
//
// Sandbox и Authorizer решают РАЗНЫЕ задачи:
//
//	Authorizer: "имеет ли плагин право отправить сообщение?"
//	Sandbox:    "может ли плагин обратиться к механизму отправки в обход
//	             Runtime?"
//
// Нужны оба: без Authorizer получаем изолированный, но всесильный
// процесс; без sandbox проверки прав обходятся напрямую через память.
//
// Требования формулируются как СВОЙСТВА, не механизмы. "Нет
// произвольного доступа к файловой системе хоста" — свойство;
// seccomp/namespaces/cgroups — способы его достижения на Linux.
// Требовать конкретный механизм означало бы сделать Android-реализацию
// невозможной по формальным причинам.
//
// Платформенная реальность (docs/threat-model.md, раздел 4):
//
//	Layer 1 (Photon: enforcement, IPC, lifecycle) — одинаково везде;
//	Layer 2 (OS sandbox) — платформо-зависим, на Android слабее и
//	требует проверки на устройстве, которой пока не было.
//
// Здесь будут платформо-специфичные реализации общего интерфейса.
