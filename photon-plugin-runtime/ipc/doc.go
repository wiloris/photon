// Package ipc — протокол Runtime <-> процесс плагина.
//
// Спецификация: docs/ipc.md.
//
// Базовый принцип: IPC transport сам по себе НЕ является authorization
// boundary. "IPC connected" не равно "permission granted" — каждый
// semantic request проходит проверку прав заново. Благодаря этому новый
// транспорт (unix socket, named pipe, Android-специфичный) добавляется
// без переписывания модели безопасности.
//
// Идентичность вызывающего определяется КАНАЛОМ, а не содержимым
// сообщения: Runtime сам запустил процесс и сам открыл соединение,
// поэтому знает, кто на другом конце. plugin_id внутри обычного запроса —
// нарушение протокола, а не поле для чтения.
//
// Планируемое разделение внутри пакета:
//
//	protocol  — типы сообщений (8 штук: HELLO, HELLO_ACK, REQUEST,
//	            RESPONSE, CANCEL, EVENT, STOP, STOP_ACK), коды ошибок
//	session   — состояние сессии: identity, таблица активных request_id
//	transport — конкретный канал; wire-format выбирается отдельно
//
// Wire-format НЕ выбран (docs/ipc.md, раздел 12): protobuf — кандидат,
// но решение отдельное. Проверочный критерий: смена формата не должна
// затрагивать семантику разделов 1-11 спецификации.
