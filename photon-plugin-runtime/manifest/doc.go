// Package manifest — парсинг и валидация манифеста плагина.
//
// Спецификация: docs/manifest.md (копия photon-core/docs/plugin-manifest.md).
//
// Базовый принцип: манифест — часть пакета, поставляемого НЕдоверенной
// стороной. Ни одно поле в нём не является источником полномочий; всё,
// что там написано, — заявление автора плагина, а не факт.
//
// Пакет НЕ содержит и не должен содержать:
//   - выданные права (granted) — это состояние Runtime в ports.Storage;
//   - trust level — определяется Runtime по источнику и подписи;
//   - состояние плагина — определяет supervisor по факту.
//
// Зависимости: только стандартная библиотека и photon-core/ports.
// Не импортирует другие пакеты runtime — манифест разбирается до того,
// как что-либо запущено.
