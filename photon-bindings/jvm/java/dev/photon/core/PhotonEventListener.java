package dev.photon.core;

/**
 * Слушатель событий Photon.
 *
 * Контракт целиком задан C ABI и мостом; см.
 * photon-bindings/docs/jni-events.md. Существенное для реализующего:
 *
 * <ul>
 *   <li>метод вызывается СИНХРОННО на потоке доставки ядра. Мост не заводит
 *       ни очереди, ни исполнителя: переход на другой поток (например, на
 *       UI-поток Compose) — ответственность вызывающего слоя;</li>
 *   <li>вызовы никогда не параллельны и приходят в порядке приёма: следующее
 *       событие не начнёт доставляться, пока не вернулось предыдущее;</li>
 *   <li>метод, который не возвращается, останавливает поток событий своего
 *       инстанса и задерживает {@code destroy} — это свойство C ABI, а не
 *       ограничение моста;</li>
 *   <li>исключение из метода фиксируется мостом и гасится, доставка
 *       продолжается, слушатель НЕ отцепляется;</li>
 *   <li>из тела метода разрешено обращаться к тому же инстансу, включая
 *       закрытие: реентерабельное уничтожение возвращает управление
 *       немедленно;</li>
 *   <li>поток событий может иметь ПРОПУСКИ при устойчивом отставании
 *       получателя — сервер роняет события при переполнении своего буфера.
 *       Логика, построенная на событиях, обязана восстанавливаться явным
 *       действием и не имеет права предполагать полноту потока.</li>
 * </ul>
 */
public interface PhotonEventListener {

    /**
     * @param eventJson конверт события; поле {@code "type"} определяет, как
     *                  разбирать остальное. Сегодня эмитируются CONNECTED,
     *                  MESSAGE и NETWORK_CHANGED. Строка принадлежит
     *                  вызывающему только на время вызова в C; сюда она
     *                  приходит уже скопированной в JVM-heap.
     */
    void onEvent(String eventJson);
}
