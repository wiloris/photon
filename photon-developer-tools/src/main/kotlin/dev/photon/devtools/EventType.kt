package dev.photon.devtools

/*
 * Единственное место, где из event_json достаётся поле "type".
 *
 * Прежде этот разбор существовал четырьмя копиями — в Dashboard, LogView,
 * NetworkLab и ReconnectLab, — и это было записано техническим долгом
 * (ROADMAP, Phase 16, Dashboard). Копии опасны не дублированием строк, а тем,
 * что расходятся молча: одна лаборатория начала бы считать событие
 * `NETWORK_CHANGED`, а соседняя — неизвестным, и расхождение выглядело бы как
 * дефект ядра, а не как разный разбор.
 *
 * Разбор остаётся регулярным выражением, а не разбором JSON: C ABI отдаёт
 * событие строкой (`photon_core.h`, ADR-045), типов ровно три, и заводить
 * зависимость от JSON-библиотеки ради одного поля инструменту не нужно.
 * Поведение сохранено дословно — то же выражение, что было во всех четырёх
 * копиях.
 */

private val TYPE_FIELD = Regex("\"type\"\\s*:\\s*\"([A-Z_]+)\"")

/**
 * Значение поля `type` или null, если его нет.
 *
 * null означает «в событии нет разбираемого типа»: битый JSON, чужая форма,
 * пустая строка. Что показывать вместо него, решает вызывающий — Dashboard,
 * LogView и NetworkLab печатают `?`, ReconnectLab относит такое событие к
 * [MarkKind.OTHER_EVENT].
 */
fun eventType(eventJson: String): String? =
    TYPE_FIELD.find(eventJson)?.groupValues?.get(1)
