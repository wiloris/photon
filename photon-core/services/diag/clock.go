// Часы диагностики — две раздельные роли (ADR-130 §2.3, поправка 2026-10-23).
//
//  1. Монотонные часы (monotime) — время событий и все длительности:
//     at_mono_ms записи, dur_us/wait_us/exec_us/commit_us, время в состоянии
//     соединения, uptime. Не зависят от перевода системных часов; читаются
//     на каждое событие.
//  2. Календарные часы (wallNow) — ОДИН раз, при создании инстанса:
//     instance_start_wall_ms. На каждое событие не читаются. Календарное
//     время события — только оценка instance_start_wall_ms + at_mono_ms; после
//     перевода системных часов она расходится с настоящим временем на
//     величину перевода.

// wallNow — календарные часы. Переменная, а не прямой вызов time.Now, только
// ради теста перевода системных часов (clock_test.go): тест подменяет её,
// чтобы воспроизвести перевод вперёд и назад без прав root.
var wallNow = time.Now

// monotime — монотонные часы среды исполнения Go, наносекунды.
//
// НАЗНАЧЕНИЕ. Одно чтение часов на событие вместо двух у time.Now (тот
// читает и реальное, и монотонное время). На хосте, где ядро отбраковало TSC и
// часы идут по HPET (так на Ryzen 5 5600H этой машины), чтение стоит ~1.4 мкс,
// и пара чтений (p99 3.3 мкс) одна превышала порог записи §5.4 (2 мкс); одно
// чтение — p99 1.7 мкс. Замеры — measurements/2026-10-23-prototype и
// 2026-10-23-after.
//
// ОГРАНИЧЕНИЯ.
//   - runtime.nanotime — внутренняя функция среды исполнения; к ней ходят
//     через go:linkname. Это единственный linkname в рабочем коде пакета, и он
//     изолирован здесь: остальной код зовёт monotime и о linkname не знает.
//   - Значение — наносекунды от неопределённой точки (не Unix): осмысленны
//     только разности. Поэтому at_mono_ms считается от startMono инстанса.
//   - Тот же источник, что у монотонной части time.Now (CLOCK_MONOTONIC на
//     Linux): перевод системных часов на него не влияет.
//
// ПРИ ОБНОВЛЕНИИ Go.
//   - Go 1.23 ограничил linkname на внутренности runtime, но runtime.nanotime
//     оставлен доступным как широко используемый (список в исходниках
//     runtime). Ядро сейчас собирается Go 1.22 (go.mod; NoNewPrivs).
//   - Если доступ закроют, сборка упадёт ЗДЕСЬ, явно, а не молча.
//   - Обязательная проверка после смены версии Go: TestMonotimeMatchesTimeNow
//     (clock_test.go) — значения идут вперёд и согласованы с time.Since; и
//     повтор замера §5.6 (TestMeasureRecordLatency) — порог p99 держится на
//     одном чтении часов.
//   - Запасной путь, если linkname станет недоступен: time.Now (два чтения) и
//     новый замер; при HPET порог §5.4 тогда, по замерам, не выполняется.
//
