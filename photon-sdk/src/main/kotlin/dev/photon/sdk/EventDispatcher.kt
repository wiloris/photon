package dev.photon.sdk

import java.util.concurrent.CopyOnWriteArrayList

/**
 * Мультиплексор слушателей поверх единственного нативного колбэка
 * (ADR-062 D3, `sdk-api.md` §3).
 *
 * C ABI держит ОДНОГО адресата на инстанс; несколько слушателей обслуживает
 * этот класс. Диспетчеризация остаётся выше ABI и не появляется ни в C, ни
 * в JNI.
 *
 * Отдельный класс, а не часть [PhotonClient], по одной причине: так вся
 * семантика §3 проверяется тестами **без нативной библиотеки**. Правила,
 * которые проверяются только на живом сервере, проверяются редко.
 *
 * Нормативные свойства (§3), каждое держится тестом:
 *  - доставка идёт по СНИМКУ набора; `add`/`remove` во время доставки не
 *    влияют на текущее событие и не бросают;
 *  - порядок обхода — порядок регистрации;
 *  - исключение слушателя не отменяет доставку остальным;
 *  - перехватывается `Throwable`, а не `Exception`;
 *  - перехваченное подаётся в `uncaughtExceptionHandler` текущего потока
 *    синхронно, до вызова следующего слушателя;
 *  - исключение самого обработчика подавляется и повторно не подаётся;
 *  - наружу не выходит ничего: [dispatch] вызывается из нативного колбэка.
 */
internal class EventDispatcher {

    /**
     * `CopyOnWriteArrayList` — не «потокобезопасный список вообще», а ровно
     * требуемая семантика: итерация идёт по снимку, сделанному в её начале,
     * поэтому изменение набора во время доставки на текущее событие не
     * влияет и `ConcurrentModificationException` не даёт. Порядок обхода —
     * порядок добавления.
     */
    private val listeners = CopyOnWriteArrayList<PhotonEventListener>()

    fun add(listener: PhotonEventListener) {
        listeners.add(listener)
    }

    /**
     * Снимает слушателя.
     *
     * Гарантия **слабая и именно такая**: после возврата слушатель не
     * включается в новые снимки, но доставку события, для которого он уже
     * попал в снимок, отписка не отменяет. Сильная версия означала бы
     * ожидание внутри `remove`, а `remove` типично зовут из самого
     * слушателя — то есть изнутри идущей доставки, и это был бы дедлок.
     */
    fun remove(listener: PhotonEventListener) {
        listeners.remove(listener)
    }

    fun count(): Int = listeners.size

    /**
     * Снимает всех слушателей.
     *
     * Вызывается закрытием клиента ПОСЛЕ возврата из `Photon_Destroy`
     * (`sdk-api.md` §8 L9): до этого момента доставка ещё возможна, и
     * очистка отняла бы событие у тех, кому оно обещано снимком. Смысл —
     * не дать клиенту, пережившему приложение, удерживать его объекты.
     */
    fun clear() {
        listeners.clear()
    }

    /**
     * Разбирает конверт и раздаёт событие слушателям.
     *
     * Вызывается из нативного колбэка, поэтому **не бросает никогда**:
     * исключение отсюда пересекло бы границу JNI.
     */
    fun dispatch(eventJson: String) {
        val event = EventParser.parse(eventJson)
        for (listener in listeners) {
            try {
                listener.onEvent(event)
            } catch (t: Throwable) {
                report(t)
            }
        }
    }

    /**
     * Отдаёт отказ слушателя обработчику необработанных исключений текущего
     * потока.
     *
     * Почему `currentThread().uncaughtExceptionHandler`, а не
     * `getDefaultUncaughtExceptionHandler()`: второй возвращает null, если
     * приложение ничего не поставило, и отказ стал бы невидим совсем.
     * Первый разрешается в обработчик приложения, когда он задан, и в
     * `ThreadGroup` — когда нет; `ThreadGroup` печатает трассировку в
     * `System.err`.
     *
     * SDK своего обработчика не заводит и default НИКОГДА не устанавливает:
     * это глобальный ресурс приложения.
     *
     * Исключение самого обработчика подавляется здесь же и повторно ему не
     * подаётся: сломан ровно тот механизм, через который мы сообщаем о
     * поломках, и второй заход по кругу лишь удвоил бы отказ.
     */
    private fun report(t: Throwable) {
        try {
            val thread = Thread.currentThread()
            thread.uncaughtExceptionHandler?.uncaughtException(thread, t)
        } catch (ignored: Throwable) {
            // Намеренно пусто — см. выше.
        }
    }
}
