package dev.photon.sdk

/**
 * Получатель событий Photon.
 *
 * Вызывается **синхронно, на потоке доставки ядра**: ни очереди, ни
 * исполнителя между ядром и слушателем нет. Переход на UI-поток — дело
 * вызывающего слоя.
 *
 * Два следствия, которые обязан учитывать каждый слушатель:
 *
 *  - **не блокироваться надолго.** Очереди между насосом и потребителем нет
 *    намеренно, поэтому медленный слушатель замедляет приём событий из сети
 *    (измерено: блокировка на 2 с даёт паузу между доставками ровно 2 с);
 *  - **поток не постоянен.** Мост присоединяет поток к JVM на каждый вызов
 *    и отсоединяет после, поэтому `Thread.currentThread()` от события к
 *    событию разный, а `ThreadLocal` не переживает доставку.
 *
 * Исключение из слушателя доставку остальным не отменяет и границу JNI не
 * пересекает — см. [PhotonClient.addEventListener].
 */
public fun interface PhotonEventListener {
    public fun onEvent(event: PhotonEvent)
}
