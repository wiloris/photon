// Package sdk — клиентская библиотека для авторов плагинов Photon.
//
// ОТДЕЛЬНЫЙ МОДУЛЬ, не подпакет photon-plugin-runtime. Разделение
// физическое, а не организационное, потому что это разные trust
// boundaries (ADR-030):
//
//	Plugin SDK      <- исполняется ВНУТРИ недоверенного процесса плагина
//	    |
//	  Plugin        <- сторонний код
//	    | IPC
//	Plugin Runtime  <- часть платформы, принимает решения о правах
//	    |
//	Photon Core
//
// Направление зависимостей (обязательное):
//
//	photon-core
//	    ^
//	    | uses
//	photon-plugin-runtime
//	    ^
//	    | НЕ импортирует runtime implementation
//	photon-plugin-sdk
//	    ^
//	    | depends only on SDK
//	  Plugin
//
// Что это означает практически:
//   - SDK НЕ импортирует photon-plugin-runtime: код SDK живёт в
//     недоверенном процессе, и импорт кода Runtime означал бы, что
//     логика принятия решений о правах компилируется внутрь того, кого
//     она должна ограничивать;
//   - SDK НЕ импортирует photon-core напрямую: плагин не обращается к
//     ядру, только к Runtime через IPC;
//   - единственный канал связи с Runtime — IPC (docs/ipc.md в
//     photon-plugin-runtime).
//
// Без физического разделения на два модуля со временем неизбежно
// появляется цикл runtime -> sdk -> runtime либо случайный импорт
// Runtime API в код плагина, и граница доверия размывается незаметно.
//
// Пакет пока пуст: реализация появится после manifest/ipc в Runtime,
// потому что SDK — клиент уже определённого протокола, а не наоборот.
